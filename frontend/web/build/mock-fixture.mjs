// Writes the mock world to a data folder in the exporter's file layout, so the build can be tried without real data.
// Every file says "mock": true and meta.json says source "mock": the production gate rejects such a folder.
import { rm, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import * as mock from '../site/mock.js';

export async function writeFixture(dir) {
  await rm(dir, { recursive: true, force: true });
  await mkdir(join(dir, 'players'), { recursive: true });
  await mkdir(join(dir, 'clubs'), { recursive: true });
  const w = (name, value) => writeFile(join(dir, name), JSON.stringify(value));
  const rankings = mock.rankings();
  await w('meta.json', { source: 'mock', mock: true, asOf: rankings.asOf, generatedAt: new Date().toISOString(), note: 'Fictional data generated by build/mock-fixture.mjs. Never publish.' });
  await w('rankings.json', rankings);
  await w('clubs.json', mock.clubs());
  await w('leagues.json', mock.leagues());
  await w('week.json', mock.week());
  for (const p of rankings.players) await w(`players/${p.id}.json`, mock.player(p.id));
  for (const c of mock.clubs()) await w(`clubs/${c.id}.json`, mock.club(c.id));
}
